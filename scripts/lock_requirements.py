"""Writes backend/requirements.lock: the exact version of every Python package in backend/.venv, which bootstrap
installs (stage 3) instead of resolving backend/requirements.txt's ranges again on the VDI. Run it after the full
backend suite has passed in backend/.venv, and commit the lock with the release:

    backend\\.venv\\Scripts\\python.exe scripts\\lock_requirements.py --tests "479 passed"

The header records the Python the suite passed on; preflight warns when the VDI's is older (docs/VDI-SETUP.md
section A). requirements.txt stays the source of the ranges; the lock must satisfy it (tests/test_client_install.py).
"""
import argparse
import datetime
import platform
import subprocess
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1] / "backend"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--tests", required=True, help='what the full suite reported, e.g. "479 passed"')
    args = parser.parse_args()
    venv_python = BACKEND / ".venv" / "Scripts" / "python.exe"
    version = subprocess.run([str(venv_python), "-c", "import sys; print('.'.join(map(str, sys.version_info[:3])))"],
                             capture_output=True, text=True, check=True).stdout.strip()
    frozen = subprocess.run([str(venv_python), "-m", "pip", "freeze", "--disable-pip-version-check"],
                            capture_output=True, text=True, check=True).stdout
    lines = sorted((l for l in frozen.splitlines() if l and not l.startswith("#")), key=str.lower)
    header = [
        "# The exact versions bootstrap installs (stage 3), from wheels only. Generated by scripts/lock_requirements.py",
        "# from backend/.venv after the full backend suite passed there; regenerate it the same way, never by hand.",
        f"# tested-python: {version}",
        f"# tested-on: {platform.system()} {platform.machine()}, {datetime.date.today().isoformat()}, suite {args.tests}",
    ]
    (BACKEND / "requirements.lock").write_text("\n".join(header + lines) + "\n", encoding="utf-8", newline="\n")
    print(f"backend/requirements.lock: {len(lines)} packages, tested on Python {version}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
