using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis;

namespace Fingerprinting.Analysis;

/// <summary>
/// Enumerates and parses a project's C# source files for the Roslyn-syntax
/// extractors (Attribute, Inheritance, EntryPoint, and the namespace-using
/// pass of FrameworkReference) and for step 4's entry-point inventory, so
/// both steps read exactly the same file set. Excludes generated code and caps the file
/// count per 21-APPLICATION-FINGERPRINTING.md Part G. Never touches semantic
/// analysis — Part A4 keeps that off by default.
/// </summary>
public static class SourceFileScanner
{
    public const int MaxFilesPerProject = 5000;

    private static readonly string[] GeneratedFileSuffixes =
        [".designer.cs", ".g.cs", ".g.i.cs", ".assemblyinfo.cs"];

    /// <param name="IsGenerated">Only ever true when the scan was asked to
    /// include generated code.</param>
    public sealed record SourceFile(string RelativePath, string AbsolutePath, bool IsGenerated = false);

    public sealed record ScanResult(IReadOnlyList<SourceFile> Files, bool Truncated);

    /// <param name="includeGenerated">Include generated files, flagged
    /// <see cref="SourceFile.IsGenerated"/>. Off for every extractor except
    /// where the generated code is itself the evidence: dotnet-svcutil puts a
    /// WCF client's binding in its generated Reference.cs.</param>
    public static ScanResult EnumerateCSharpFiles(
        string repositoryRoot, string projectDirectory, CancellationToken cancellationToken, bool includeGenerated = false)
    {
        var files = new List<SourceFile>();
        var truncated = false;

        foreach (var absolutePath in FileSystemWalk.EnumerateFiles(projectDirectory, cancellationToken))
        {
            if (!absolutePath.EndsWith(".cs", StringComparison.OrdinalIgnoreCase))
            {
                continue;
            }

            var generated = IsGenerated(absolutePath);
            if (generated && !includeGenerated)
            {
                continue;
            }

            if (files.Count >= MaxFilesPerProject)
            {
                truncated = true;
                break;
            }

            files.Add(new SourceFile(FileSystemWalk.ToRepositoryRelativePath(repositoryRoot, absolutePath), absolutePath, generated));
        }

        return new ScanResult(files, truncated);
    }

    /// <summary>Syntax-only parse — never throws on code that does not
    /// compile, which is the entire point of Level 3 vs Level 4 (Part A4).</summary>
    public static async Task<SyntaxNode> ParseAsync(string absolutePath, CancellationToken cancellationToken)
    {
        var text = await File.ReadAllTextAsync(absolutePath, cancellationToken);
        var tree = CSharpSyntaxTree.ParseText(text, cancellationToken: cancellationToken);
        return await tree.GetRootAsync(cancellationToken);
    }

    private static bool IsGenerated(string path)
    {
        var name = Path.GetFileName(path);
        if (GeneratedFileSuffixes.Any(suffix => name.EndsWith(suffix, StringComparison.OrdinalIgnoreCase)))
        {
            return true;
        }

        try
        {
            using var reader = new StreamReader(path);
            for (var i = 0; i < 3; i++)
            {
                var line = reader.ReadLine();
                if (line is null)
                {
                    break;
                }

                if (line.Contains("<auto-generated", StringComparison.OrdinalIgnoreCase))
                {
                    return true;
                }
            }
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            // Unreadable file — not our call to make it a warning here; the
            // extractor's own read attempt will surface and skip it.
        }

        return false;
    }
}
