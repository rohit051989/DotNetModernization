"""The experiment's comparison report (36-COPILOT-ENHANCED-CONVERSION Part F): one scorecard per run, identical
for every run, from the verifier's output and the engine run record — never from what an engine reported.

    python -m app.experiment.report --config ..\\experiments\\copilot-eshoponweb\\experiment.yaml

Writes `REPORT.md` beside the configuration. A run not yet verified is listed as such.
"""
import argparse
import json
import sys
from pathlib import Path

import yaml

from app import models
from app.conversion import planner
from app.engine import runs as engine_runs
from app.experiment.prepare import copilot_runs

ARM3_LABEL = "arm3"


def scorecard(verification: dict | None, record: dict | None) -> dict:
    if verification is None:
        return {"verdict": "not verified"}
    clean = verification["cleanRun"]
    executed = sum(p.get("total", 0) for p in clean["projects"].values())
    passed = sum(p.get("passed", 0) for p in clean["projects"].values())
    base_total = verification["baseline"].get("total")
    kept = next((c for c in verification["checks"] if c["id"] == "kept"), {})
    rd, im, d = verification["rediscovery"], verification["impact"], verification["diff"]
    return {
        "verdict": verification["verdict"], "reasons": verification["reasons"],
        "builds": "yes" if clean["built"] else "no",
        "tests": f"{passed} of {base_total} passed ({executed} executed)" if clean["built"] else "not run",
        "testsKept": kept.get("detail", ""),
        "workItems": f"{len(rd['resolved'])} resolved, {len(rd['remaining'])} remaining, {len(rd['introduced'])} introduced (of {rd['before']})",
        "offTarget": len(rd["offTarget"]),
        "outsidePrediction": len(im["unpredicted"]), "predictedUntouched": len(im["predictedUntouched"]),
        "diff": f"{d['filesTouched']} files, +{d['linesAdded']} -{d['linesDeleted']}",
        "interventions": len(record["interventions"]) if record else None,
        "premiumRequests": record.get("premiumRequests") if record else None,
        "elapsedMinutes": record.get("elapsedMinutes") if record else None,
        "model": record.get("model") if record else None,
        "identity": f"{record['signedInIdentity']} / {record['organisation']}" if record else None,
    }


def build(db, config: dict) -> str:
    home = planner.RUNS / config["engagement"] / config["repository"] / "verification"
    rows = [dict(r, card=None) for r in copilot_runs(config)]
    arm3 = next((a for a in config["arms"] if "ref" in a), None)
    if arm3:
        rows.append({"label": ARM3_LABEL, "arm": 3, "name": arm3["name"], "branch": arm3["ref"]})
    for r in rows:
        f = home / r["label"] / "verification.json"
        verification = json.loads(f.read_text(encoding="utf-8")) if f.exists() else None
        run = db.query(models.EngineRun).filter_by(engagement_id=config["engagement"], label=r["label"]).one_or_none()
        r["card"] = scorecard(verification, engine_runs.as_dict(run) if run else None)

    out = ["# Comparison report — Copilot-enhanced conversion, first experiment", "",
           "> Generated by `python -m app.experiment.report`. Every figure comes from the platform's verifier or the run",
           "> record; nothing an engine reported is evidence. Spec: `docs/36-COPILOT-ENHANCED-CONVERSION.md` Part F.", "",
           f"Subject `{config['repository']}` from `{config['baseline_commit']}`, engagement `{config['engagement']}`.", ""]
    if arm3:
        out += [f"**Arm 3 covers the {arm3['scope']}, not OpenShift readiness.** It is compared with the other arms on "
                "the version upgrade alone: its OpenShift work items are expected to remain.", ""]
    out += ["## Scorecard", "",
            "| Run | Arm | Verdict | Builds | Tests vs baseline | Work items | Outside prediction | Diff | Interventions | Premium requests | Minutes |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        c = r["card"]
        if c["verdict"] == "not verified":
            out.append(f"| `{r['label']}` | {r['arm']} | not verified | | | | | | | | |")
            continue
        out.append(f"| `{r['label']}` | {r['arm']} | **{c['verdict']}** | {c['builds']} | {c['tests']} | {c['workItems']} | "
                   f"{c['outsidePrediction']} | {c['diff']} | {c['interventions'] if c['interventions'] is not None else '-'} | "
                   f"{c['premiumRequests'] if c['premiumRequests'] is not None else '-'} | "
                   f"{c['elapsedMinutes'] if c['elapsedMinutes'] is not None else '-'} |")
    out += ["", "## Reasons per run", ""]
    for r in rows:
        c = r["card"]
        out += [f"### {r['label']} — {r['name']}", ""]
        if c["verdict"] == "not verified":
            out += ["Not verified yet.", ""]
            continue
        out += [f"Verdict **{c['verdict']}**. Tests kept: {c['testsKept']}"]
        if c.get("identity"):
            out.append(f"Signed in: {c['identity']}; model {c['model']}.")
        out += [""] + [f"- {x}" for x in c["reasons"]] + [""]
    out += ["## What the result means (Part F)", "",
            "- **Arm 2 clearly ahead of arm 1**: the enhancement is the platform's value; proceed to the second app.",
            "- **No clear difference**: inspect which inputs the engine ignored, and whether instructions activated.",
            "- **Arm 3 ahead on the version upgrade**: keep deterministic changes for the platform's codemods.", "",
            "Two runs per arm cannot separate skill from luck on their own; read the per-run reasons, not only the verdicts.", ""]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    from app.db import SessionLocal

    parser = argparse.ArgumentParser(prog="python -m app.experiment.report", description=__doc__.split("\n\n")[0])
    parser.add_argument("--config", required=True, type=Path)
    args = parser.parse_args(argv)
    config = yaml.safe_load(args.config.read_text(encoding="utf-8"))
    db = SessionLocal()
    try:
        text = build(db, config)
    finally:
        db.close()
    target = args.config.resolve().parent / "REPORT.md"
    target.write_text(text, encoding="utf-8", newline="\n")
    print(target)
    return 0


if __name__ == "__main__":
    sys.exit(main())
