"""Calibrate the verifier for one experiment (36-COPILOT-ENHANCED-CONVERSION Part E) and write CALIBRATION.md.

    python -m app.experiment.calibrate --config <RUNS_DIR>\\<engagement>\\experiments\\<name>\\experiment.yaml
    python -m app.experiment.calibrate --config ... --render-only      (CALIBRATION.md from the last verifications)

Runs the verifier on the baseline commit (label `calibration-baseline`), which must read NOT PROVEN, nothing
converted, and on arm 3's branch where the experiment has one (label `arm3`). CALIBRATION.md is rendered from the
verifier's own output (verification.json): the verdicts, every reason, every check, the measured baseline and the
impact comparison. Nothing in it is written by hand.
"""
import argparse
import json
import sys
from pathlib import Path

import yaml

from app.conversion import planner

BASELINE_LABEL = "calibration-baseline"
ARM3_LABEL = "arm3"


def labelled(config: dict, label: str) -> str:
    """A verification label within the experiment's generation: generation 1 kept the bare labels; a later one is
    prefixed (`v2-calibration-baseline`), so recalibrating never overwrites an earlier generation's verification."""
    from app.experiment.prepare import generation

    g = generation(config)
    return label if g == 1 else f"v{g}-{label}"


def _section(title: str, v: dict, expectation: str | None, config: dict) -> list[str]:
    from app.experiment import instrument

    rd, im, d = v["rediscovery"], v["impact"], v["diff"]
    platform = v.get("platform")
    out = [f"## {title}", "", f"`{v['ref']}` at `{v['tip'][:8]}`, verified {v['verifiedAt']} by verifier {v['verifier']['version']}"
           f" at platform commit `{platform['commit'][:12] if platform else 'not recorded'}`.", ""]
    if instrument.mismatch(config, v):
        out += [f"**Not the experiment's instrument:** {instrument.mismatch(config, v)}. Calibrate again at the pinned commit.", ""]
    if expectation:
        out += [f"Expected: {expectation}", ""]
    out += [f"**{v['verdict']}.**", ""] + [f"- {r}" for r in v["reasons"]] + ["", "| Check | State | Detail |", "|---|---|---|"]
    out += [f"| {c['label']} | {c['state']} | {c['detail'].replace('|', '/')} |" for c in v["checks"]]
    b = v["baseline"]
    source = f"conversion plan `{b['plan'][:8]}`" if b.get("plan") else ("the verifier at the base commit" if b.get("measuredBy")
                                                                         else f"none ({b.get('why', 'not measured')})")
    out += ["", f"Measured baseline: {b.get('total', 0)} test(s), from {source}.",
            f"Work items: {rd['before']} before; {len(rd['resolved'])} resolved, {len(rd['remaining'])} remaining, "
            f"{len(rd['introduced'])} introduced; projects not on the target framework: {len(rd['offTarget'])}.",
            f"Diff: {d['filesTouched']} file(s), +{d['linesAdded']} -{d['linesDeleted']}, {d['commits']} commit(s).",
            f"Impact: {len(im['unpredicted'])} changed file(s) not predicted"
            + (f" ({', '.join(f'`{p}`' for p in im['unpredicted'][:10])})" if im["unpredicted"] else "")
            + f"; {len(im['predictedUntouched'])} of {im['predictedFiles']} predicted file(s) untouched.",
            f"Re-discovery isolation: the client database was only read (scratch database, dropped).", ""]
    return out


def render(config: dict) -> str:
    home = planner.RUNS / config["engagement"] / config["repository"] / "verification"
    out = [f"# Verifier calibration — {config.get('title', config['repository'])}", "",
           "> Generated by `python -m app.experiment.calibrate` from the verifier's output "
           f"(`{home}`). Do not edit: run it again.", ""]
    found = False
    for label, title, expectation in (
            (BASELINE_LABEL, f"Baseline `{config['baseline_commit']}`", "NOT PROVEN, nothing converted"),
            (ARM3_LABEL, "Arm 3", None)):
        f = home / labelled(config, label) / "verification.json"
        if f.exists():
            found = True
            out += _section(title, json.loads(f.read_text(encoding="utf-8")), expectation, config)
    if not found:
        out += ["Not calibrated yet.", ""]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    from app.db import SessionLocal
    from app.engine import verifier

    parser = argparse.ArgumentParser(prog="python -m app.experiment.calibrate", description=__doc__.split("\n\n")[0])
    parser.add_argument("--config", required=True, type=Path)
    parser.add_argument("--render-only", action="store_true", help="write CALIBRATION.md from existing verifications")
    parser.add_argument("--out", type=Path, help="write CALIBRATION.md into this folder instead (with --render-only)")
    args = parser.parse_args(argv)
    if args.out and not args.render_only:
        parser.error("--out needs --render-only")
    config_path = args.config.resolve()
    config = yaml.safe_load(config_path.read_text(encoding="utf-8"))
    if not args.render_only:
        db = SessionLocal()
        try:
            targets = [(labelled(config, BASELINE_LABEL), config["baseline_commit"])]
            targets += [(labelled(config, ARM3_LABEL), a["ref"]) for a in config["arms"] if "ref" in a]
            for label, ref in targets:
                report = verifier.verify(db, engagement_id=config["engagement"], slug=config["repository"],
                                         base=config["baseline_commit"], ref=ref, label=label, config=config,
                                         baseline_plan=config.get("baseline_plan"))
                print(f"{label}: {report['verdict']}")
        finally:
            db.close()
    target = (args.out.resolve() if args.out else config_path.parent) / "CALIBRATION.md"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render(config), encoding="utf-8", newline="\n")
    print(target)
    return 0


if __name__ == "__main__":
    sys.exit(main())
